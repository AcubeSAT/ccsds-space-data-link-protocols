    static constexpr uint8_t SpacePacketDataLengthFieldPosition = 5; // 5th and 6th bytes constitute the data field length

    /**
     * @brief Returns the total length of a space packet (as defined in CCSDS Space Packet Protocol).
     */
    static uint16_t getSpacePacketLength(const etl::span<uint8_t>& packetSource) {
        // plus one is added because the field actually contains the data field length, reduced by one
        return (static_cast<uint16_t>(packetSource[SpacePacketDataLengthFieldPosition - 1]) << 8) |
               (static_cast<uint16_t>(packetSource[SpacePacketDataLengthFieldPosition])) + SpacePacketPrimaryHeaderLength + 1;
    }

