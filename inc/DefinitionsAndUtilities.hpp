    /**
     * @brief Return the packet version number of a packet, if it is defined in the enumeration.
     */
    static etl::optional<PacketVersionNumber> getPacketVersionNumber(uint8_t firstPacketOctet) {
        if (const uint8_t packetVersion = firstPacketOctet >> 5; packetVersion == static_cast<uint8_t>(PacketVersionNumber::SPACE_PACKET)) {
            return PacketVersionNumber::SPACE_PACKET;
        } else {
            return PacketVersionNumber::ENCAPSULATION_PACKET;
        }
    }


    static constexpr uint16_t MaxExpectedSpacePacketSize = 128;
