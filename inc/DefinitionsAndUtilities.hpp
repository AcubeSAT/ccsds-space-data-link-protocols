    /**
     *  | VCID (6 bits) | SCID(10 bits) |
     */
    using VcidScidKey = uint16_t;

    /**
     *  | EMPTY (10 bits) | MAPID (6 bits) | VCID (6 bits) | SCID (10 bits) |
     */
    using MapidVcidScidKey = uint32_t;

    inline VcidScidKey constructVcidScidKey(const uint8_t vcid, const uint16_t scid) {
        return static_cast<VcidScidKey>(vcid) << 10 | scid;
    }

    inline MapidVcidScidKey constructMapidVcidScidKey(const uint8_t mapid,
                                                      const uint8_t vcid,
                                                      const uint16_t scid) {
        return (static_cast<MapidVcidScidKey>(mapid) << (6 + 10))
             | (static_cast<MapidVcidScidKey>(vcid) << 10)
             | scid;
    }

    inline etl::tuple<uint8_t, uint16_t> extractVcidScid(VcidScidKey key) {
        uint8_t vcid = static_cast<uint8_t>(key >> 10);   // top 6 bits
        uint16_t scid = static_cast<uint16_t>(key & 0x03FFU);
        return {vcid, scid};
    }

    inline etl::tuple<uint8_t, uint8_t, uint16_t> extractMapidVcidScidKey(MapidVcidScidKey key) {
        uint8_t mapid = static_cast<uint8_t>(key >> (6 + 10));
        uint8_t vcid  = static_cast<uint8_t>((key >> 10) & 0x3FU);
        uint16_t scid = static_cast<uint16_t>(key & 0x03FFU);
        return {mapid, vcid, scid};
    }

